/**
 * Прямоугольник одной парты хаба. Координаты — в пикселях всего канваса
 * (как в PNG слоя мебели), а не относительно комнаты.
 */
export interface HubDeskLayout {
  /** Левый верхний угол парты по X. */
  x: number;
  /** Левый верхний угол парты по Y. */
  y: number;
  /** Ширина парты, включая все её части (визуал). */
  width: number;
  /** Высота парты, включая ножки (визуал). Y нижнего края = y + height. */
  height: number;
  /** Высота нижней полосы, которой парта стоит на полу (непроходимая зона). */
  footprintHeight: number;
}